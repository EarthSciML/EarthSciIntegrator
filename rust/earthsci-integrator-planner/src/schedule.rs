/// The kind of a schedule node.
#[derive(Debug, Clone, PartialEq)]
pub enum Kind {
    /// `leaf` (`coupled: false`) or `coupled`, with its operators in order.
    Leaf {
        ops: Vec<String>,
        coupled: bool,
    },
    Sequence(Vec<Node>),
    Strang(Vec<Node>),
    Subcycle(Box<Node>),
    Every(Box<Node>),
    SplitExplicit,
    Map,
    Solve,
}

/// A schedule node with its path, id and run-config pointer.
#[derive(Debug, Clone, PartialEq)]
pub struct Node {
    /// The node's path from the root (`root`, `root.0`, `root.1.every`).
    pub path: String,
    /// The id given in the run config.
    pub given_id: Option<String>,
    /// Where the node is in the run config; `/schedule` for every node of
    /// the `"auto"` schedule.
    pub pointer: String,
    /// Whether the node was generated by `"schedule": "auto"`.
    pub generated: bool,
    /// The node's object as written (or generated).
    pub value: Map<String, Value>,
    pub kind: Kind,
}

impl Node {
    /// The id the plan writes: the given one, else the path (§7.1).
    pub fn id(&self) -> &str {
        self.given_id.as_deref().unwrap_or(&self.path)
    }

    /// The pointer of one of the node's keys (the node itself for a
    /// generated node).
    pub fn key_ptr(&self, key: &str) -> String {
        if self.generated {
            self.pointer.clone()
        } else {
            ptr(&self.pointer, key)
        }
    }

    /// The node's children.
    pub fn children(&self) -> Vec<&Node> {
        match &self.kind {
            Kind::Sequence(c) | Kind::Strang(c) => c.iter().collect(),
            Kind::Subcycle(c) | Kind::Every(c) => vec![c],
            _ => vec![],
        }
    }

    /// The node and its descendants in tree order (preorder).
    pub fn preorder(&self) -> Vec<&Node> {
        let mut out = vec![self];
        for c in self.children() {
            out.extend(c.preorder());
        }
        out
    }

    /// The leaf and coupled nodes in tree order.
    pub fn leaves(&self) -> Vec<&Node> {
        self.preorder()
            .into_iter()
            .filter(|n| matches!(n.kind, Kind::Leaf { .. }))
            .collect()
    }

    /// The pointer of the i-th operator of a leaf or coupled node.
    pub fn op_ptr(&self, i: usize) -> String {
        let key = if self.value.contains_key("coupled") {
            "coupled"
        } else {
            "leaf"
        };
        if self.generated {
            return self.pointer.clone();
        }
        let at = ptr(&self.pointer, key);
        if self.value.get(key).is_some_and(Value::is_array) {
            ptr(&at, i)
        } else {
            at
        }
    }

    /// Whether the node gives a `dt`.
    pub fn dt_given(&self) -> bool {
        self.value.contains_key("dt")
    }
}

fn names(v: Option<&Value>) -> Vec<String> {
    crate::operators::strings(v)
        .unwrap_or_default()
        .into_iter()
        .map(str::to_string)
        .collect()
}

/// Builds the node tree of a written schedule.
fn parse(v: &Value, path: String, pointer: String, generated: bool) -> Node {
    let value = v.as_object().cloned().unwrap_or_default();
    let given_id = value.get("id").and_then(Value::as_str).map(str::to_string);
    let child = |key: &str, sub: String| {
        let p = if generated {
            pointer.clone()
        } else {
            ptr(&pointer, key)
        };
        parse(&value[key], format!("{path}.{sub}"), p, generated)
    };
    let list = |key: &str| -> Vec<Node> {
        value[key]
            .as_array()
            .map(|a| {
                a.iter()
                    .enumerate()
                    .map(|(i, c)| {
                        let p = if generated {
                            pointer.clone()
                        } else {
                            ptr(&ptr(&pointer, key), i)
                        };
                        parse(c, format!("{path}.{i}"), p, generated)
                    })
                    .collect()
            })
            .unwrap_or_default()
    };
    let kind = if value.contains_key("leaf") {
        Kind::Leaf {
            ops: names(value.get("leaf")),
            coupled: false,
        }
    } else if value.contains_key("coupled") {
        Kind::Leaf {
            ops: names(value.get("coupled")),
            coupled: true,
        }
    } else if value.contains_key("sequence") {
        Kind::Sequence(list("sequence"))
    } else if value.contains_key("strang") {
        Kind::Strang(list("strang"))
    } else if value.contains_key("subcycle") {
        Kind::Subcycle(Box::new(child("subcycle", "subcycle".into())))
    } else if value.contains_key("every") {
        Kind::Every(Box::new(child("every", "every".into())))
    } else if value.contains_key("split_explicit") {
        Kind::SplitExplicit
    } else if value.contains_key("map") {
        Kind::Map
    } else {
        Kind::Solve
    };
    Node {
        path,
        given_id,
        pointer,
        generated,
        value,
        kind,
    }
}

/// The schedule tree: the run config's, or for `"schedule": "auto"` the
/// composition of §5.5.5 (D72): one leaf per non-empty locality class,
/// holding that class's operators sorted by name, in the order global,
/// stencil, column, pointwise, every option `"auto"`; one leaf is the root,
/// two or more a `sequence`, or a `strang` when the model's
/// `solver.splitting` is `"strang"`.
pub fn tree(rc: &RunConfig, info: &ModelInfo, ops: &BTreeMap<String, Operator>) -> Node {
    let schedule = rc.at("/schedule").cloned().unwrap_or(Value::Null);
    if schedule.as_str() != Some("auto") {
        return parse(&schedule, "root".into(), "/schedule".into(), false);
    }
    let mut leaves = Vec::new();
    for class in [
        Class::Global,
        Class::Stencil,
        Class::Column,
        Class::Pointwise,
    ] {
        // `ops` iterates in code-point order of the names.
        let members: Vec<&String> = ops
            .values()
            .filter(|o| o.locality.class == class)
            .map(|o| &o.name)
            .collect();
        if !members.is_empty() {
            leaves.push(json!({"leaf": members, "alg": "auto"}));
        }
    }
    let generated = match leaves.len() {
        1 => leaves.pop().unwrap_or_default(),
        _ => {
            let strang = info
                .file
                .solver
                .as_ref()
                .and_then(|s| s.splitting.as_deref())
                == Some("strang");
            if strang {
                json!({"strang": leaves})
            } else {
                json!({"sequence": leaves})
            }
        }
    };
    parse(&generated, "root".into(), "/schedule".into(), true)
}

/// A duration (spec/run-config.md §2.2) in seconds: a literal, or a
/// parameter's default. A name that is not a parameter with a scalar default
/// is `name_unresolved` or `name_wrong_kind` (rule 2).
///
/// A parameter whose default is not a positive finite number is
/// `run_config_invalid` at the duration's key (spec/run-config.md §2.2,
/// spec/plan.md §7.1). The literal 0 a `phase` may be never comes from a
/// parameter.
pub fn duration(v: &Value, pointer: &str, info: &ModelInfo) -> Result<f64> {
    if let Some(x) = literal_duration(v) {
        return Ok(x);
    }
    let name = v.as_str().unwrap_or_default();
    if !info.is_name(name) {
        return Err(refuse(
            codes::NAME_UNRESOLVED,
            pointer,
            format!("{name} is not a name of the flattened model"),
        ));
    }
    let x = info
        .flat
        .parameters
        .get(name)
        .and_then(|p| p.default_scalar())
        .ok_or_else(|| {
            refuse(
                codes::NAME_WRONG_KIND,
                pointer,
                format!("{name} is not a parameter with a scalar default in seconds"),
            )
        })?;
    if !(x.is_finite() && x > 0.0) {
        return Err(refuse(
            codes::RUN_CONFIG_INVALID,
            pointer,
            format!("{name} has the default {x}, and a duration is positive"),
        ));
    }
    Ok(x)
}

/// Whether an id has the path form (`root`, `root.0`, `root.1.every`).
fn is_path_form(id: &str) -> bool {
    let Some(rest) = id.strip_prefix("root") else {
        return false;
    };
    rest.split('.').skip(1).all(|seg| {
        seg == "subcycle"
            || seg == "every"
            || (!seg.is_empty() && seg.bytes().all(|b| b.is_ascii_digit()))
    }) && (rest.is_empty() || rest.starts_with('.'))
}

/// What the schedule checks need besides the tree.
pub struct CheckContext<'a> {
    pub rc: &'a RunConfig,
    pub info: &'a ModelInfo,
    pub ops: &'a BTreeMap<String, Operator>,
    pub interval: Interval,
}

/// spec/plan.md §7.1: the unsupported nodes of §0.1 in tree order, then
/// spec/run-config.md §8 rules 3, 5–9, 12, 13 and 15, in rule order.
pub fn check(root: &Node, cx: &CheckContext) -> Result<()> {
    check_unsupported(root, cx)?;
    check_step_limits(cx)?;
    rule_2(root, cx)?;
    rule_3(root, cx)?;
    rule_5(root, cx)?;
    rule_6(root, cx)?;
    rule_7(root)?;
    rule_8(root)?;
    rule_9(root, cx)?;
    rule_12(root, cx)?;
    rule_13(root)?;
    rule_15(root, cx)?;
    Ok(())
}

/// A name in a `limits` list: resolved first (`name_unresolved`;
/// `name_wrong_kind` when it is not an observed), then refused,
/// `unsupported_step_limit`, at its pointer (§7.1).
fn observed_limit(l: &Value, at: String, info: &ModelInfo) -> Result<()> {
    let name = l.as_str().unwrap_or_default();
    if !info.is_name(name) {
        return Err(refuse(
            codes::NAME_UNRESOLVED,
            at,
            format!("{name} is not a name of the flattened model"),
        ));
    }
    if !info.is_observed(name) {
        return Err(refuse(
            codes::NAME_WRONG_KIND,
            at,
            format!("the step limit {name} is not an observed"),
        ));
    }
    Err(refuse(
        codes::UNSUPPORTED_STEP_LIMIT,
        at,
        format!("the observed step limit {name} needs a limit operator (U6, M4b)"),
    ))
}

/// The observeds in `step.limits`, entries in written order, after the
/// schedule's unsupported constructs (§7.1).
fn check_step_limits(cx: &CheckContext) -> Result<()> {
    if let Some(Value::Array(limits)) = cx.rc.at("/step/limits") {
        for (i, l) in limits.iter().enumerate() {
            if l.is_string() {
                observed_limit(l, ptr("/step/limits", i), cx.info)?;
            }
        }
    }
    Ok(())
}

/// `map`, `solve` and `split_explicit` nodes, and observed limits of a
/// `subcycle`, in tree order. (`coupled` with algebraic operators cannot
/// occur: algebraic equations were refused at §4 step 6.)
fn check_unsupported(root: &Node, cx: &CheckContext) -> Result<()> {
    for n in root.preorder() {
        match n.kind {
            Kind::Map => {
                return Err(refuse(
                    codes::UNSUPPORTED_MAP_OPERATOR,
                    n.pointer.clone(),
                    "map nodes need U6 (M4b)",
                ))
            }
            Kind::Solve => {
                return Err(refuse(
                    codes::UNSUPPORTED_SOLVE_NODE,
                    n.pointer.clone(),
                    "solve nodes need U6 (M4b)",
                ))
            }
            Kind::SplitExplicit => {
                return Err(refuse(
                    codes::UNSUPPORTED_SPLIT_EXPLICIT,
                    n.pointer.clone(),
                    "split_explicit nodes arrive at M7",
                ))
            }
            Kind::Subcycle(_) => {
                if let Some(Value::Array(limits)) = n.value.get("limits") {
                    for (i, l) in limits.iter().enumerate() {
                        if l.is_string() {
                            observed_limit(l, ptr(&n.key_ptr("limits"), i), cx.info)?;
                        }
                    }
                }
            }
            _ => {}
        }
    }
    Ok(())
}

/// A name that must be a model parameter (`bind_dt` keys).
fn must_be_parameter(name: &str, at: String, info: &ModelInfo) -> Result<()> {
    if !info.is_name(name) {
        return Err(refuse(
            codes::NAME_UNRESOLVED,
            at,
            format!("{name} is not a name of the flattened model"),
        ));
    }
    if !info.is_parameter(name) {
        return Err(refuse(
            codes::NAME_WRONG_KIND,
            at,
            format!("{name} is not a parameter"),
        ));
    }
    Ok(())
}

/// A name that must be a state (`control.abstol` keys, `domain.nonnegative`
/// entries).
fn must_be_state(name: &str, at: String, info: &ModelInfo) -> Result<()> {
    if !info.is_name(name) {
        return Err(refuse(
            codes::NAME_UNRESOLVED,
            at,
            format!("{name} is not a name of the flattened model"),
        ));
    }
    if !info.is_state(name) {
        return Err(refuse(
            codes::NAME_WRONG_KIND,
            at,
            format!("{name} is not a state variable"),
        ));
    }
    Ok(())
}

/// A `bind_dt` object's keys, in code-point order, must be parameters.
fn bind_dt_keys(b: Option<&Value>, at: &str, info: &ModelInfo) -> Result<()> {
    if let Some(m) = b.and_then(Value::as_object) {
        let keys: BTreeSet<&String> = m.keys().collect();
        for k in keys {
            must_be_parameter(k, ptr(at, k), info)?;
        }
    }
    Ok(())
}

/// A duration's names resolve (rule 2), and a parameter's default is a
/// positive finite number.
fn check_duration(v: Option<&Value>, at: String, info: &ModelInfo) -> Result<()> {
    match v {
        Some(v)
            if v.as_i64() != Some(0)
                && v.as_str() != Some("step")
                && v.as_str() != Some("accumulated") =>
        {
            duration(v, &at, info).map(|_| ())
        }
        _ => Ok(()),
    }
}

/// A node's parameter-name durations, in this order: `dt`, `control.dt0`,
/// `control.dtmin`, `control.dtmax`, `period`, `phase`, each `limits`
/// entry's `max`, then each `frozen` entry's `period` and `phase`.
fn node_durations(n: &Node, info: &ModelInfo) -> Result<()> {
    let v = &n.value;
    check_duration(v.get("dt"), n.key_ptr("dt"), info)?;
    for k in ["dt0", "dtmin", "dtmax"] {
        let c = v.get("control").and_then(|c| c.get(k));
        check_duration(c, ptr(&n.key_ptr("control"), k), info)?;
    }
    check_duration(v.get("period"), n.key_ptr("period"), info)?;
    check_duration(v.get("phase"), n.key_ptr("phase"), info)?;
    if let Some(Value::Array(limits)) = v.get("limits") {
        for (i, l) in limits.iter().enumerate() {
            let at = ptr(&ptr(&n.key_ptr("limits"), i), "max");
            check_duration(l.get("max"), at, info)?;
        }
    }
    if let Some(Value::Array(frozen)) = v.get("frozen") {
        for (i, f) in frozen.iter().enumerate() {
            let at = ptr(&n.key_ptr("frozen"), i);
            check_duration(f.get("period"), ptr(&at, "period"), info)?;
            check_duration(f.get("phase"), ptr(&at, "phase"), info)?;
        }
    }
    Ok(())
}

/// Rule 2 for the names §5.1.3 has not checked, in §7.1's order: the
/// operators' `bind_dt` keys; the parameter-name durations outside the
/// schedule; per node in tree order its durations, `bind_dt` keys,
/// per-variable `control.abstol` keys and `domain.nonnegative` entries; then
/// the `precision` keys.
///
/// SPEC FINDING (§7.1 rule 2 item 3): the order of one node's several
/// parameter-name durations is not given; [`node_durations`] fixes one.
fn rule_2(root: &Node, cx: &CheckContext) -> Result<()> {
    let info = cx.info;
    if let Some(ops) = cx.rc.at("/operators").and_then(Value::as_object) {
        let names: BTreeSet<&String> = ops.keys().collect();
        for name in names {
            let at = ptr(&ptr("/operators", name), "bind_dt");
            bind_dt_keys(ops[name].get("bind_dt"), &at, info)?;
        }
    }
    check_duration(cx.rc.at("/step/dt"), "/step/dt".into(), info)?;
    if let Some(Value::Array(limits)) = cx.rc.at("/step/limits") {
        for (i, l) in limits.iter().enumerate() {
            check_duration(l.get("max"), ptr(&ptr("/step/limits", i), "max"), info)?;
        }
    }
    for k in ["hit_multiples", "resolution"] {
        check_duration(cx.rc.at(&format!("/step/{k}")), ptr("/step", k), info)?;
    }
    check_duration(cx.rc.at("/output/saveat"), "/output/saveat".into(), info)?;
    if let Some(Value::Array(sinks)) = cx.rc.at("/output/sinks") {
        for (i, s) in sinks.iter().enumerate() {
            check_duration(
                s.get("saveat"),
                ptr(&ptr("/output/sinks", i), "saveat"),
                info,
            )?;
        }
    }
    for n in root.preorder() {
        node_durations(n, info)?;
        bind_dt_keys(n.value.get("bind_dt"), &n.key_ptr("bind_dt"), info)?;
        let control = n.key_ptr("control");
        if let Some(Value::Object(abstol)) = n.value.get("control").and_then(|c| c.get("abstol")) {
            let keys: BTreeSet<&String> = abstol.keys().collect();
            for k in keys {
                must_be_state(k, ptr(&ptr(&control, "abstol"), k), info)?;
            }
        }
        if let Some(Value::Array(nn)) = n.value.get("domain").and_then(|d| d.get("nonnegative")) {
            let at = ptr(&n.key_ptr("domain"), "nonnegative");
            for (i, s) in nn.iter().enumerate() {
                must_be_state(s.as_str().unwrap_or_default(), ptr(&at, i), info)?;
            }
        }
    }
    if let Some(precision) = cx.rc.at("/precision").and_then(Value::as_object) {
        let ids: BTreeSet<&str> = root.preorder().iter().map(|n| n.id()).collect();
        let keys: BTreeSet<&String> = precision.keys().collect();
        for k in keys {
            if k != "default" && !cx.ops.contains_key(k.as_str()) && !ids.contains(k.as_str()) {
                return Err(refuse(
                    codes::NAME_UNRESOLVED,
                    ptr("/precision", k),
                    format!("the precision key {k} names no operator, node or default"),
                ));
            }
        }
    }
    Ok(())
}

/// The operator names a node's `frozen` list holds, with their pointers.
fn frozen_ops(n: &Node) -> Vec<(String, String)> {
    let mut out = Vec::new();
    if let Some(Value::Array(list)) = n.value.get("frozen") {
        for (i, f) in list.iter().enumerate() {
            let at = ptr(&n.key_ptr("frozen"), i);
            match f {
                Value::String(s) => out.push((s.clone(), at)),
                Value::Object(o) => {
                    if let Some(s) = o.get("every").and_then(Value::as_str) {
                        out.push((s.to_string(), ptr(&at, "every")));
                    }
                }
                _ => {}
            }
        }
    }
    out
}

/// The operator names an `IMEXEuler` leaf's `imex` parts hold (locality
/// names are not operator names), with their pointers `<node>/imex/<part>/<i>`
/// (`<node>/imex/<part>` for a part written as one string): `explicit`, then
/// `implicit`, entries in written order. An `imex` key on a leaf whose
/// written `alg` is not `IMEXEuler` is ignored (spec/plan.md §7.1).
///
/// SPEC FINDING (§7.1 rule 3): the place of `imex` entries among a node's
/// operator names, and which part comes first, are not stated; they are
/// checked after the leaf's operators and before its `frozen` entries,
/// `explicit` before `implicit`.
fn imex_ops(n: &Node) -> Vec<(String, String)> {
    let mut out = Vec::new();
    if n.value.get("alg").and_then(Value::as_str) != Some("IMEXEuler") {
        return out;
    }
    let Some(imex) = n.value.get("imex") else {
        return out;
    };
    for part in ["explicit", "implicit"] {
        let at = ptr(&n.key_ptr("imex"), part);
        match imex.get(part) {
            Some(Value::String(s)) if Class::parse(s).is_none() => out.push((s.clone(), at)),
            Some(Value::Array(list)) => {
                for (i, e) in list.iter().enumerate() {
                    if let Some(s) = e.as_str().filter(|s| Class::parse(s).is_none()) {
                        out.push((s.to_string(), ptr(&at, i)));
                    }
                }
            }
            _ => {}
        }
    }
    out
}

/// Rule 3: every operator the schedule names (a leaf's or coupled node's
/// operators, its `imex` entries, its `frozen` entries) is defined or an
/// existing default operator. Rule 6 then checks only the partition.
fn rule_3(root: &Node, cx: &CheckContext) -> Result<()> {
    for n in root.preorder() {
        let mut named: Vec<(String, String)> = Vec::new();
        if let Kind::Leaf { ops, .. } = &n.kind {
            named.extend(
                ops.iter()
                    .enumerate()
                    .map(|(i, o)| (o.clone(), n.op_ptr(i))),
            );
        }
        named.extend(imex_ops(n));
        named.extend(frozen_ops(n));
        for (op, at) in named {
            if !cx.ops.contains_key(&op) {
                return Err(refuse(
                    codes::OPERATOR_UNDEFINED,
                    at,
                    format!("{op} is neither a defined operator nor an existing default operator"),
                ));
            }
        }
    }
    Ok(())
}

/// Rule 5 (spec/plan.md §7.1, D84): every operator is advanced somewhere (a
/// `leaf` or `coupled` node, or a `frozen` entry of one, names it), and no
/// operator is named by two `leaf` or `coupled` nodes (`frozen` entries do
/// not count toward "twice"). A default operator advanced nowhere is
/// reported at `/schedule`.
fn rule_5(root: &Node, cx: &CheckContext) -> Result<()> {
    let mut advanced: BTreeSet<String> = BTreeSet::new();
    let mut first: BTreeMap<String, String> = BTreeMap::new();
    for n in root.preorder() {
        if let Kind::Leaf { ops, .. } = &n.kind {
            for (i, op) in ops.iter().enumerate() {
                if first.insert(op.clone(), n.id().to_string()).is_some() {
                    return Err(refuse(
                        codes::OPERATOR_ADVANCED_TWICE,
                        n.op_ptr(i),
                        format!("{op} is advanced by two leaves"),
                    ));
                }
                advanced.insert(op.clone());
            }
        }
        advanced.extend(frozen_ops(n).into_iter().map(|(o, _)| o));
    }
    for (name, op) in cx.ops {
        if !advanced.contains(name) {
            let at = if op.is_default {
                "/schedule".to_string()
            } else {
                ptr("/operators", name)
            };
            return Err(refuse(
                codes::OPERATOR_NOT_ADVANCED,
                at,
                format!("{name} is advanced by no node of the schedule"),
            ));
        }
    }
    Ok(())
}

/// The operators of a leaf an `imex` part names: operator names, and
/// locality names expanded to the leaf's operators of that class.
fn imex_part(v: Option<&Value>, leaf: &[String], ops: &BTreeMap<String, Operator>) -> Vec<String> {
    let mut out = Vec::new();
    for entry in names(v) {
        match Class::parse(&entry) {
            Some(class) => out.extend(
                leaf.iter()
                    .filter(|o| ops.get(*o).is_some_and(|op| op.locality.class == class))
                    .cloned(),
            ),
            None => out.push(entry),
        }
    }
    out
}

/// A leaf's `imex` partition as lists of operator names in leaf order
/// (§7.1): `explicit` omitted is everything not implicit. `None` when the
/// partition leaves an operator in neither part or in both, or names one
/// the leaf does not advance.
pub fn imex_partition(
    imex: &Value,
    leaf: &[String],
    ops: &BTreeMap<String, Operator>,
) -> Option<(Vec<String>, Vec<String>)> {
    let implicit = imex_part(imex.get("implicit"), leaf, ops);
    let explicit = match imex.get("explicit") {
        Some(e) => imex_part(Some(e), leaf, ops),
        None => leaf
            .iter()
            .filter(|o| !implicit.contains(o))
            .cloned()
            .collect(),
    };
    let mut seen = BTreeSet::new();
    for o in implicit.iter().chain(&explicit) {
        if !leaf.contains(o) || !seen.insert(o) {
            return None;
        }
    }
    if seen.len() != leaf.len() || implicit.is_empty() {
        return None;
    }
    let order = |part: &[String]| -> Vec<String> {
        leaf.iter().filter(|o| part.contains(o)).cloned().collect()
    };
    Some((order(&explicit), order(&implicit)))
}

/// Rule 6: an `IMEXEuler` leaf's partition puts each of its operators in
/// exactly one part.
fn rule_6(root: &Node, cx: &CheckContext) -> Result<()> {
    for n in root.leaves() {
        let Kind::Leaf { ops, .. } = &n.kind else {
            continue;
        };
        if n.value.get("alg").and_then(Value::as_str) != Some("IMEXEuler") {
            continue;
        }
        let Some(imex) = n.value.get("imex") else {
            return Err(refuse(
                codes::IMEX_PARTITION_INVALID,
                n.pointer.clone(),
                "an IMEXEuler leaf needs imex; there is no default partition",
            ));
        };
        if imex_partition(imex, ops, cx.ops).is_none() {
            return Err(refuse(
                codes::IMEX_PARTITION_INVALID,
                n.key_ptr("imex"),
                "the imex partition leaves an operator of the leaf in neither part, or in both",
            ));
        }
    }
    Ok(())
}

/// Rule 7: a path-form id only on the node whose path it is, and no id
/// twice.
fn rule_7(root: &Node) -> Result<()> {
    let mut seen = BTreeSet::new();
    for n in root.preorder() {
        let Some(id) = &n.given_id else {
            continue;
        };
        let at = n.key_ptr("id");
        if is_path_form(id) && *id != n.path {
            return Err(refuse(
                codes::NODE_ID_RESERVED,
                at,
                format!("{id} is the path of another node; a path-form id belongs to the node at that path"),
            ));
        }
        if !seen.insert(id.clone()) {
            return Err(refuse(
                codes::DUPLICATE_NODE_ID,
                at,
                format!("the node id {id} is used twice"),
            ));
        }
    }
    Ok(())
}

/// Rule 8: a `hold: "tendency"` `every` node's child is a single leaf.
fn rule_8(root: &Node) -> Result<()> {
    for n in root.preorder() {
        if let Kind::Every(child) = &n.kind {
            let hold = n.value.get("hold").and_then(Value::as_str) == Some("tendency");
            let leaf = matches!(&child.kind, Kind::Leaf { coupled: false, .. });
            if hold && !leaf {
                return Err(refuse(
                    codes::HOLD_TENDENCY_CHILD_NOT_LEAF,
                    n.key_ptr("every"),
                    "an every node with hold: tendency needs a single leaf as its child",
                ));
            }
        }
    }
    Ok(())
}

/// `eps(x)` of spec/methods.md §10: the spacing of binary64 at `|x|`.
fn eps(x: f64) -> f64 {
    let x = x.abs();
    if x == 0.0 {
        return f64::from_bits(1);
    }
    f64::from_bits(x.to_bits() + 1) - x
}

/// `λ(a, b)` of spec/plan.md §7.3: `|a − b| ≤ 100 ε(max(|a|, |b|))`.
fn lands(a: f64, b: f64) -> bool {
    (a - b).abs() <= 100.0 * eps(a.abs().max(b.abs()))
}

/// Whether the tstop `tau` is on the fixed step (spec/plan.md §7.3):
/// `λ(τ, tf)`; or, with `r` the integer nearest `(τ − t0)/dt`, some
/// `k ∈ {r − 1, r, r + 1}`, `k ≥ 1`, has `λ(τ, t0 + k·dt)` and the macro
/// step from `t0 + (k − 1)·dt` is not a stop step (spec/methods.md §10 with
/// `h = dt`, `t_stop = tf`).
fn on_fixed_boundary(tau: f64, t0: f64, tf: f64, dt: f64) -> bool {
    if lands(tau, tf) {
        return true;
    }
    let r = ((tau - t0) / dt).round();
    [r - 1.0, r, r + 1.0]
        .into_iter()
        .filter(|k| *k >= 1.0)
        .any(|k| {
            let b = t0 + k * dt;
            let ta = if k == 1.0 { t0 } else { t0 + (k - 1.0) * dt };
            let stop_step = dt + 100.0 * eps(ta.abs().max(tf.abs())) >= tf - ta;
            lands(tau, b) && !stop_step
        })
}

/// The multiples `j·m` of a duration in `(t0, tf]`, counted from model time
/// zero (spec/run-config.md §1.1).
///
/// Each multiple is the binary64 product `j·m`. One within the landing
/// tolerance `λ` of `tf` is `tf` itself; one within `λ` of `t0` is
/// excluded; the others are kept when they lie in `(t0, tf]` (D83, the
/// "Fixed boundaries" landing rule of spec/run-config.md §5). So `m` 0.1 on
/// `[0, 0.3]` gives 0.1, 0.2 and 0.3, not 0.30000000000000004.
fn multiples(m: f64, iv: Interval) -> impl Iterator<Item = f64> {
    // One candidate either side of the quotients, filtered by the products.
    let first = (iv.start / m).floor() as i64;
    let last = (iv.end / m).floor() as i64 + 1;
    (first..=last).filter_map(move |j| {
        let t = j as f64 * m;
        if lands(t, iv.end) {
            Some(iv.end)
        } else if lands(t, iv.start) {
            None
        } else {
            (t > iv.start && t <= iv.end).then_some(t)
        }
    })
}

/// Whether the root is a single `leaf` or `coupled` node whose `dt` is
/// omitted or numeric, which lands on tstops inside the macro step.
fn root_lands_itself(root: &Node) -> bool {
    matches!(root.kind, Kind::Leaf { .. })
        && !matches!(
            root.value.get("dt").and_then(Value::as_str),
            Some("step") | Some("accumulated")
        )
}

/// Rule 9, for the tstops M2 can know: `hit_multiples` and the adjoint's
/// observation times (spec/plan.md §7.3, D83): for `over: "saveat"` the
/// multiples of `output.saveat` from model time zero in `(t0, tf]` (`tf`
/// alone without it), for `over: "final"` `tf`, which is always on the
/// step, and none for `over: "time"`.
///
/// SPEC FINDING (§7.3): "the adjoint's key" for an observation time off the
/// step is read as `/adjoint/functional/over`.
fn rule_9(root: &Node, cx: &CheckContext) -> Result<()> {
    let Some(dt) = cx.rc.at("/step/dt") else {
        return Ok(());
    };
    if root_lands_itself(root) {
        return Ok(());
    }
    let dt = duration(dt, "/step/dt", cx.info)?;
    let iv = cx.interval;
    if let Some(m) = cx.rc.at("/step/hit_multiples") {
        let m = duration(m, "/step/hit_multiples", cx.info)?;
        if let Some(tau) = multiples(m, iv).find(|t| !on_fixed_boundary(*t, iv.start, iv.end, dt)) {
            return Err(refuse(
                codes::TSTOP_OFF_FIXED_STEP,
                "/step/hit_multiples",
                format!("the tstop {tau} s is not t0 plus a multiple of step.dt = {dt} s"),
            ));
        }
    }
    if cx.rc.at("/adjoint/functional/over").and_then(Value::as_str) == Some("saveat") {
        if let Some(s) = cx.rc.at("/output/saveat") {
            let s = duration(s, "/output/saveat", cx.info)?;
            if let Some(tau) =
                multiples(s, iv).find(|t| !on_fixed_boundary(*t, iv.start, iv.end, dt))
            {
                return Err(refuse(
                    codes::TSTOP_OFF_FIXED_STEP,
                    "/adjoint/functional/over",
                    format!("the observation time {tau} s is not t0 plus a multiple of step.dt = {dt} s"),
                ));
            }
        }
    }
    Ok(())
}

/// Rule 12: with neither `step.dt` nor `step.limits`, the root is a single
/// adaptive `leaf` or `coupled` node.
fn rule_12(root: &Node, cx: &CheckContext) -> Result<()> {
    let has = |k: &str| cx.rc.at(&format!("/step/{k}")).is_some();
    if has("dt") || has("limits") {
        return Ok(());
    }
    if matches!(root.kind, Kind::Leaf { .. }) && !root.dt_given() {
        return Ok(());
    }
    Err(refuse(
        codes::STEP_CONTROL_MISSING,
        "/step",
        "step has neither dt nor limits, and the schedule root is not a single adaptive leaf",
    ))
}

/// Rule 13: a leaf with `dt` omitted uses a method with an error estimate.
fn rule_13(root: &Node) -> Result<()> {
    for n in root.leaves() {
        let alg = n.value.get("alg").and_then(Value::as_str).unwrap_or("auto");
        if alg != "auto" && !n.dt_given() && !has_error_estimate(alg) {
            return Err(refuse(
                codes::ADAPTIVE_WITHOUT_ERROR_ESTIMATE,
                n.key_ptr("alg"),
                format!("{alg} has no error estimate, so a leaf using it must give dt"),
            ));
        }
    }
    Ok(())
}

/// Rule 15: an adaptive leaf that binds a parameter to its step gives
/// `control.dt0`. The leaf's own `bind_dt` is checked first, then its
/// operators', in leaf order.
fn rule_15(root: &Node, cx: &CheckContext) -> Result<()> {
    let binds_leaf = |b: Option<&Value>| {
        b.and_then(Value::as_object)
            .is_some_and(|m| m.values().any(|v| v.as_str() == Some("leaf")))
    };
    for n in root.leaves() {
        let Kind::Leaf { ops, .. } = &n.kind else {
            continue;
        };
        if n.dt_given() || n.value.get("control").and_then(|c| c.get("dt0")).is_some() {
            continue;
        }
        let mut at = None;
        if binds_leaf(n.value.get("bind_dt")) {
            at = Some(n.key_ptr("bind_dt"));
        } else if let Some(op) = ops
            .iter()
            .find(|o| binds_leaf(cx.ops.get(*o).and_then(|op| op.bind_dt.as_ref())))
        {
            at = Some(ptr(&ptr("/operators", op), "bind_dt"));
        }
        if let Some(at) = at {
            return Err(refuse(
                codes::BIND_DT_LEAF_WITHOUT_DT0,
                at,
                "an adaptive leaf binds a parameter to its step but gives no control.dt0",
            ));
        }
    }
    Ok(())
}

/// The class of a leaf: the coarsest locality of its operators.
pub fn leaf_class(n: &Node, ops: &BTreeMap<String, Operator>) -> Class {
    match &n.kind {
        Kind::Leaf { ops: names, .. } => names
            .iter()
            .filter_map(|o| ops.get(o))
            .map(|o| o.locality.class)
            .max()
            .unwrap_or(Class::Pointwise),
        _ => Class::Pointwise,
    }
}

/// A leaf's resolved `reltol` (default 1e-3).
pub fn reltol(n: &Node) -> f64 {
    n.value
        .get("control")
        .and_then(|c| c.get("reltol"))
        .and_then(Value::as_f64)
        .unwrap_or(1e-3)
}

/// Writes the resolved tree (§7.1). `strategy` gives each leaf's resolved
/// method (§5.5.3).
pub fn write(
    n: &Node,
    info: &ModelInfo,
    ops: &BTreeMap<String, Operator>,
    strategy: &dyn Fn(&Node) -> Result<LeafStrategy>,
) -> Result<Value> {
    let mut out = Map::new();
    out.insert("id".into(), json!(n.id()));
    let dur = |v: &Value, at: String| duration(v, &at, info).map(|x| json!(x));
    match &n.kind {
        Kind::Leaf {
            ops: names,
            coupled,
        } => {
            let s = strategy(n)?;
            out.insert(
                if *coupled { "coupled" } else { "leaf" }.into(),
                json!(names),
            );
            out.insert("alg".into(), json!(s.alg));
            let given = |k: &str| n.value.get(k);
            if let Some(dt) = given("dt") {
                let v = match dt.as_str() {
                    Some("step") | Some("accumulated") => dt.clone(),
                    _ => dur(dt, n.key_ptr("dt"))?,
                };
                out.insert("dt".into(), v);
            }
            let control_in = given("control")
                .and_then(Value::as_object)
                .cloned()
                .unwrap_or_default();
            let cptr = |k: &str| ptr(&n.key_ptr("control"), k);
            let mut control = Map::new();
            control.insert(
                "reltol".into(),
                control_in.get("reltol").cloned().unwrap_or(json!(0.001)),
            );
            control.insert(
                "abstol".into(),
                control_in.get("abstol").cloned().unwrap_or(json!(0.000001)),
            );
            control.insert("dt_scope".into(), json!(s.dt_scope));
            if n.dt_given() {
                if let Some(m) = control_in.get("maxiters") {
                    control.insert("maxiters".into(), m.clone());
                }
            } else {
                let controller = control_in
                    .get("controller")
                    .and_then(Value::as_str)
                    .filter(|c| *c != "auto")
                    .unwrap_or("PI");
                control.insert("controller".into(), json!(controller));
                control.insert(
                    "maxiters".into(),
                    control_in
                        .get("maxiters")
                        .cloned()
                        .unwrap_or(json!(1000000)),
                );
                for k in ["dt0", "dtmin", "dtmax"] {
                    if let Some(v) = control_in.get(k) {
                        control.insert(k.into(), dur(v, cptr(k))?);
                    }
                }
            }
            out.insert("control".into(), Value::Object(control));
            if forms_jacobian(&s.alg) {
                out.insert("jacobian".into(), json!(s.jacobian));
                out.insert("linsolve".into(), s.linsolve.clone().unwrap_or(Value::Null));
            }
            let domain_in = given("domain")
                .and_then(Value::as_object)
                .cloned()
                .unwrap_or_default();
            let mut domain = Map::new();
            domain.insert(
                "on_violation".into(),
                domain_in
                    .get("on_violation")
                    .cloned()
                    .unwrap_or(json!("reject")),
            );
            domain.insert(
                "check_stages".into(),
                domain_in
                    .get("check_stages")
                    .cloned()
                    .unwrap_or(json!(false)),
            );
            if let Some(nn) = domain_in.get("nonnegative") {
                domain.insert("nonnegative".into(), nn.clone());
            }
            out.insert("domain".into(), Value::Object(domain));
            if s.alg == "IMEXEuler" {
                let (explicit, implicit) = match (&s.imex_implicit, given("imex")) {
                    (Some(imp), _) => (
                        names.iter().filter(|o| !imp.contains(o)).cloned().collect(),
                        imp.clone(),
                    ),
                    (None, Some(imex)) => imex_partition(imex, names, ops).unwrap_or_default(),
                    (None, None) => (names.clone(), vec![]),
                };
                out.insert(
                    "imex".into(),
                    json!({"explicit": explicit, "implicit": implicit}),
                );
                out.insert(
                    "implicit_solve".into(),
                    given("implicit_solve")
                        .cloned()
                        .unwrap_or(json!("converged")),
                );
            }
            if s.alg == "Theta" {
                if let Some(t) = given("theta") {
                    out.insert("theta".into(), t.clone());
                }
            }
            if let Some(Value::Array(frozen)) = given("frozen") {
                let mut list = Vec::new();
                for (i, f) in frozen.iter().enumerate() {
                    let at = ptr(&n.key_ptr("frozen"), i);
                    list.push(match f {
                        Value::Object(o) => {
                            let mut e = o.clone();
                            for k in ["period", "phase"] {
                                if let Some(v) = o.get(k) {
                                    let x = if v.as_i64() == Some(0) {
                                        json!(0)
                                    } else {
                                        dur(v, ptr(&at, k))?
                                    };
                                    e.insert(k.into(), x);
                                }
                            }
                            Value::Object(e)
                        }
                        other => other.clone(),
                    });
                }
                out.insert("frozen".into(), Value::Array(list));
            }
            if let Some(b) = given("bind_dt") {
                out.insert("bind_dt".into(), b.clone());
            }
        }
        Kind::Sequence(children) | Kind::Strang(children) => {
            let key = if matches!(n.kind, Kind::Sequence(_)) {
                "sequence"
            } else {
                "strang"
            };
            let list: Result<Vec<Value>> = children
                .iter()
                .map(|c| write(c, info, ops, strategy))
                .collect();
            out.insert(key.into(), Value::Array(list?));
        }
        Kind::Subcycle(child) => {
            out.insert("subcycle".into(), write(child, info, ops, strategy)?);
            if let Some(k) = n.value.get("n") {
                out.insert("n".into(), k.clone());
            }
            if let Some(Value::Array(limits)) = n.value.get("limits") {
                let mut list = Vec::new();
                for (i, l) in limits.iter().enumerate() {
                    let at = ptr(&ptr(&n.key_ptr("limits"), i), "max");
                    list.push(json!({"max": dur(&l["max"], at)?}));
                }
                out.insert("limits".into(), Value::Array(list));
            }
        }
        Kind::Every(child) => {
            out.insert("every".into(), write(child, info, ops, strategy)?);
            out.insert(
                "period".into(),
                dur(&n.value["period"], n.key_ptr("period"))?,
            );
            let phase = match n.value.get("phase") {
                None => json!(0),
                Some(v) if v.as_i64() == Some(0) => json!(0),
                Some(v) => dur(v, n.key_ptr("phase"))?,
            };
            out.insert("phase".into(), phase);
            out.insert(
                "hold".into(),
                n.value.get("hold").cloned().unwrap_or(json!("none")),
            );
        }
        // Refused by `check`.
        Kind::SplitExplicit | Kind::Map | Kind::Solve => {}
    }
    Ok(Value::Object(out))
}

/// The smallest `{"max": d}` of a `limits` list.
type SmallestMax<'a> = dyn Fn(Option<&Value>, &str) -> Result<Option<f64>> + 'a;

/// The reference step Δ of every leaf, by node id (§5.5.4): the root
/// receives `step.dt` when fixed, else the smallest `{"max": d}` of
/// `step.limits`, else `tf − t0`; a `sequence` passes its Δ on, a `strang`
/// Δ/2 to every child but the last, a `subcycle` Δ/n or, with `limits`, the
/// smaller of Δ and its smallest `{"max": d}`, an `every` its period; a
/// leaf's Δ is its numeric `dt`, else what it receives.
pub fn reference_steps(
    root: &Node,
    rc: &RunConfig,
    info: &ModelInfo,
    iv: Interval,
) -> Result<BTreeMap<String, f64>> {
    let smallest_max = |limits: Option<&Value>, at: &str| -> Result<Option<f64>> {
        let mut best: Option<f64> = None;
        if let Some(Value::Array(list)) = limits {
            for (i, l) in list.iter().enumerate() {
                if let Some(m) = l.get("max") {
                    let d = duration(m, &ptr(&ptr(at, i), "max"), info)?;
                    best = Some(best.map_or(d, |b: f64| b.min(d)));
                }
            }
        }
        Ok(best)
    };
    let root_delta = match rc.at("/step/dt") {
        Some(dt) => duration(dt, "/step/dt", info)?,
        None => smallest_max(rc.at("/step/limits"), "/step/limits")?.unwrap_or(iv.end - iv.start),
    };
    let mut out = BTreeMap::new();
    fn walk(
        n: &Node,
        delta: f64,
        info: &ModelInfo,
        out: &mut BTreeMap<String, f64>,
        smallest_max: &SmallestMax,
    ) -> Result<()> {
        match &n.kind {
            Kind::Leaf { .. } => {
                let own = match n.value.get("dt") {
                    Some(dt)
                        if dt
                            .as_str()
                            .is_none_or(|s| s != "step" && s != "accumulated") =>
                    {
                        Some(duration(dt, &n.key_ptr("dt"), info)?)
                    }
                    _ => None,
                };
                out.insert(n.id().to_string(), own.unwrap_or(delta));
            }
            Kind::Sequence(c) => {
                for child in c {
                    walk(child, delta, info, out, smallest_max)?;
                }
            }
            Kind::Strang(c) => {
                for (i, child) in c.iter().enumerate() {
                    let d = if i + 1 == c.len() { delta } else { delta / 2.0 };
                    walk(child, d, info, out, smallest_max)?;
                }
            }
            Kind::Subcycle(child) => {
                let d = match n.value.get("n").and_then(Value::as_u64) {
                    Some(k) => delta / k as f64,
                    None => smallest_max(n.value.get("limits"), &n.key_ptr("limits"))?
                        .map_or(delta, |m| delta.min(m)),
                };
                walk(child, d, info, out, smallest_max)?;
            }
            Kind::Every(child) => {
                let p = duration(&n.value["period"], &n.key_ptr("period"), info)?;
                walk(child, p, info, out, smallest_max)?;
            }
            _ => {}
        }
        Ok(())
    }
    walk(root, root_delta, info, &mut out, &smallest_max)?;
    Ok(out)
}

