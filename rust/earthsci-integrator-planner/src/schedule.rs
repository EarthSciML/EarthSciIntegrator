    fn fixed_boundaries() {
        // dt 0.1 on [0, 0.3]: 0.3 falls on 3 × 0.1 = 0.30000000000000004.
        assert!(on_fixed_boundary(0.3, 0.0, 1.0, 0.1));
        assert!(on_fixed_boundary(600.0, 0.0, 3600.0, 300.0));
        assert!(!on_fixed_boundary(7.0, 0.0, 3600.0, 300.0));
        // tf is always a boundary.
        assert!(on_fixed_boundary(1000.0, 0.0, 1000.0, 300.0));
        // k ≥ 1: landing on t0 itself does not count.
        let t1 = 1.0 + eps(1.0);
        assert!(!on_fixed_boundary(t1, 1.0, 10.0, 1.0));
        // A boundary reached only by a stop step does not count: tau lands
        // on 4 = 0 + 4·1, but tf is within the stop rule's tolerance of 4,
        // so the step from 3 is a stop step, and tau is not within λ of tf.
        let e = eps(4.0);
        let (tau, tf) = (4.0 - 60.0 * e, 4.0 + 60.0 * e);
        assert!(lands(tau, 4.0) && !lands(tau, tf));
        assert!(!on_fixed_boundary(tau, 0.0, tf, 1.0));
        assert!(on_fixed_boundary(tau, 0.0, 5.0, 1.0));
        let iv = Interval {
            start: 0.0,
            end: 21.0,
        };
        assert_eq!(
            multiples(7.0, iv).collect::<Vec<_>>(),
            vec![7.0, 14.0, 21.0]
        );
        let iv = Interval {
            start: 7.0,
            end: 20.0,
        };
        assert_eq!(multiples(7.0, iv).collect::<Vec<_>>(), vec![14.0]);
        // A multiple within λ of tf is tf (3 × 0.1 = 0.30000000000000004).
        let iv = Interval {
            start: 0.0,
            end: 0.3,
        };
        assert_eq!(multiples(0.1, iv).collect::<Vec<_>>(), vec![0.1, 0.2, 0.3]);
        // One within λ of t0 is excluded, even when the product is above t0;
        // 6 × 0.1 = 0.6000000000000001 is tf.
        let iv = Interval {
            start: 0.3,
            end: 0.6,
        };
        assert_eq!(multiples(0.1, iv).collect::<Vec<_>>(), vec![0.4, 0.5, 0.6]);
        // A hit_multiples tstop of 0.1 under dt 0.1 on [0, 0.3] is on the step.
        assert!(multiples(
            0.1,
            Interval {
                start: 0.0,
                end: 0.3
            }
        )
        .all(|t| on_fixed_boundary(t, 0.0, 0.3, 0.1)));
    }
